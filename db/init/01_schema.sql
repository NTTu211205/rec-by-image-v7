-- Database schema generated from dienmayxanh_products.csv
-- PostgreSQL 13+; exactly three tables, schema mwg.
-- Product category_id uses source subcategory (62 groups), not the coarse source category_id (5 sections).
CREATE SCHEMA IF NOT EXISTS mwg;

CREATE TABLE IF NOT EXISTS mwg.categories (
    category_id VARCHAR(80) PRIMARY KEY,
    category_name TEXT NOT NULL,
    parent_category_code VARCHAR(80) NOT NULL,
    CONSTRAINT uq_categories_name_parent UNIQUE (category_name, parent_category_code)
);

CREATE TABLE IF NOT EXISTS mwg.brand (
    brand_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS mwg.product (
    product_id VARCHAR(80) PRIMARY KEY,
    product_name TEXT NOT NULL,
    description TEXT,
    category_id VARCHAR(80) NOT NULL REFERENCES mwg.categories(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    brand_id INTEGER NOT NULL REFERENCES mwg.brand(brand_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    price BIGINT NOT NULL CHECK (price >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'VND',
    image_url TEXT,
    product_url TEXT,
    availability BOOLEAN NOT NULL DEFAULT FALSE,
    colors JSONB NOT NULL DEFAULT '[]'::jsonb,
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    style JSONB NOT NULL DEFAULT '[]'::jsonb,
    placement JSONB NOT NULL DEFAULT '[]'::jsonb,
    dimensions JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS idx_mwg_product_category ON mwg.product (category_id);
CREATE INDEX IF NOT EXISTS idx_mwg_product_brand ON mwg.product (brand_id);
CREATE INDEX IF NOT EXISTS idx_mwg_product_price ON mwg.product (price);
CREATE INDEX IF NOT EXISTS idx_mwg_product_available_category ON mwg.product (category_id, price) WHERE availability;
CREATE INDEX IF NOT EXISTS idx_mwg_product_tags_gin ON mwg.product USING GIN (tags);
